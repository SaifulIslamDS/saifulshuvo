import { access, rm, writeFile } from "node:fs/promises";
import { constants } from "node:fs";
import path from "node:path";

const root = process.cwd();
const outDir = path.join(root, "out");
const emptyBlogBuildSlug = "__saifulshuvo_no_published_posts__";

try {
  await access(outDir, constants.R_OK | constants.W_OK);
} catch {
  console.error("Static export directory 'out/' does not exist. Run next build first.");
  process.exit(1);
}

// Next.js output:export currently errors when generateStaticParams() returns an
// empty array. The blog route therefore emits one build-only sentinel page when
// WordPress has zero published posts. Never deploy that page publicly.
await rm(path.join(outDir, "blog", emptyBlogBuildSlug), {
  recursive: true,
  force: true,
});

const htaccess = String.raw`# SaifulShuvo static Next.js deployment on cPanel/Apache
# Generated by scripts/prepare-cpanel-output.mjs

Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{HTTP_HOST} ^www\.saifulshuvo\.com$ [NC]
  RewriteRule ^ https://saifulshuvo.com%{REQUEST_URI} [R=301,L]
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "DENY"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()"
  Header always set Cross-Origin-Opener-Policy "same-origin-allow-popups"
  Header always set Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
  Header always set Content-Security-Policy "default-src 'self'; base-uri 'self'; object-src 'none'; frame-ancestors 'none'; form-action 'self'; img-src 'self' data: blob: https:; font-src 'self' data:; style-src 'self' 'unsafe-inline'; script-src 'self' 'unsafe-inline' https://www.googletagmanager.com https://plausible.io; connect-src 'self' https://cms.saifulshuvo.com https://*.google-analytics.com https://*.analytics.google.com https://*.googletagmanager.com https://plausible.io; manifest-src 'self'; media-src 'self' https:; worker-src 'self' blob:"

  <FilesMatch "\.(?:html?)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
  <FilesMatch "\.(?:js|css|woff2?|png|jpe?g|gif|svg|webp|avif|ico)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
</IfModule>
`;

await writeFile(path.join(outDir, ".htaccess"), htaccess, "utf8");
console.log("Removed build-only empty-blog sentinel route (if present).");
console.log("Prepared out/.htaccess for cPanel/Apache static hosting.");
